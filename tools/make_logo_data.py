# Generates src/ui/LogoData.h: the LYNX SHARE logo (by w3teal) embedded in the exe, used by the About box, the
# plugin-editor header button and the window/taskbar icon.
# Source of truth: resources/brand/lynx-share-logo.svg; tools/make_logo.py renders it to resources/lynx_badge.png
# (1024 px) and to the small-size form resources/brand/lynx-share-logo-small.png. This script embeds a 512 px version
# of the first (crisp at 200% scale; the header button rescales it down in steps), a 128 px version of the second
# (drawn where the logo is 24 physical pixels or less) and where the round badge sits inside them.
# Usage: python3 tools/make_logo_data.py   (from the repository root). scripts/check-logo.py fails when the header drifts.
import hashlib, io
from PIL import Image

SRC = "resources/lynx_badge.png"
SMALL = "resources/brand/lynx-share-logo-small.png"


def png(path, size):
    img = Image.open(path).convert("RGBA").resize((size, size), Image.LANCZOS)
    out = io.BytesIO()
    img.save(out, "PNG", optimize=True)
    return out.getvalue()


def array(name, data):
    lines = ["inline constexpr unsigned char %s[] = {" % name]
    for i in range(0, len(data), 24):
        lines.append(", ".join(str(b) for b in data[i:i + 24]) + ",")
    return lines + ["};"]


raw = open(SRC, "rb").read()
# the round badge: its left, right and bottom edges are the circle's (the ears rise above it)
a = Image.open(io.BytesIO(raw)).convert("RGBA").getchannel("A")
x0, y0, x1, y1 = a.point(lambda v: 255 if v >= 128 else 0).getbbox()
r = (x1 - x0) / 2.0
disc = ((x0 + x1) / 2.0 / a.width, (y1 - r) / a.height, r / a.width)
big, small = png(SRC, 512), png(SMALL, 128)

lines = ["#pragma once", "",
         "// LYNX SHARE logo by w3teal: %s as a 512 px PNG (png512) and the small-size form %s as a 128 px PNG" % (SRC, SMALL),
         "// (pngSmall), both with transparency.",
         "// Generated by tools/make_logo_data.py - do not edit by hand (scripts/check-logo.py verifies it).",
         "// source-sha256: " + hashlib.sha256(raw).hexdigest(),
         "// small-sha256: " + hashlib.sha256(open(SMALL, "rb").read()).hexdigest(), "",
         "namespace lynx::logo", "{",
         "// where the round badge sits in both pictures (fractions of the side): centre x, centre y, radius",
         "inline constexpr float discX = %.4ff, discY = %.4ff, discR = %.4ff;" % disc]
lines += array("png512", big) + array("pngSmall", small)
lines += ["} // namespace lynx::logo", ""]
open("src/ui/LogoData.h", "w").write("\n".join(lines))
print("png512", len(big), "bytes, pngSmall", len(small), "bytes, disc", disc)
