# Generates src/ui/LogoData.h: the app logo (dark disc + red ring + pepper) embedded in the exe, used by the About box,
# the plugin-editor header button and the window/taskbar icon.
# Source of truth: resources/brand/lynx-badge.svg, rendered to resources/lynx_badge.png (1024 px). This script embeds a
# 512 px version (crisp at 200% scale; the header button rescales it down in steps).
# Usage: python3 tools/make_logo_data.py   (from the repository root). scripts/check-logo.py fails when the header drifts.
import hashlib, io
from PIL import Image

SRC = "resources/lynx_badge.png"
SIZE = 512

raw = open(SRC, "rb").read()
img = Image.open(io.BytesIO(raw)).convert("RGBA")
bbox = img.getchannel("A").getbbox()
img = img.resize((SIZE, SIZE), Image.LANCZOS)
out = io.BytesIO()
img.save(out, "PNG", optimize=True)
data = out.getvalue()

lines = ["#pragma once", "",
         "// LYNX logo (dark disc with the vector red pepper, %d px PNG with transparency), from %s." % (SIZE, SRC),
         "// Generated by tools/make_logo_data.py - do not edit by hand (scripts/check-logo.py verifies it).",
         "// source-sha256: " + hashlib.sha256(raw).hexdigest(), "",
         "namespace lynx::logo", "{", "inline constexpr unsigned char png512[] = {"]
for i in range(0, len(data), 24):
    lines.append(", ".join(str(b) for b in data[i:i + 24]) + ",")
lines += ["};", "} // namespace lynx::logo", ""]
open("src/ui/LogoData.h", "w").write("\n".join(lines))
print(SIZE, len(data), "bytes")
