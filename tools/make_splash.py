# Generates src/ui/SplashData.h: the logo (by w3teal) from resources/lynx_logo.png, cropped and scaled for the splash screen.
# resources/lynx_logo.png is written by tools/make_logo.py from resources/brand/lynx-share-logo.svg.
# Usage: python3 tools/make_splash.py   (from the repository root)
import hashlib, io
from PIL import Image

HEIGHT = 420  # px: sharp up to 175% display scaling at the splash's drawn size

srcHash = hashlib.sha256(open("resources/lynx_logo.png", "rb").read()).hexdigest()
mark = Image.open("resources/lynx_logo.png").convert("RGBA")
mark = mark.crop(mark.getbbox())
width = round(mark.width * HEIGHT / mark.height)
mark = mark.resize((width, HEIGHT), Image.LANCZOS)
out = io.BytesIO()
mark.save(out, "PNG", optimize=True)
data = out.getvalue()

lines = ["#pragma once", "",
         "// The logo (by w3teal) for the splash screen (resources/lynx_logo.png cropped to its outline, %dx%d PNG with transparency)." % (width, HEIGHT),
         "// Generated by tools/make_splash.py - do not edit by hand (scripts/check-logo.py verifies it).",
         "// source-sha256: " + srcHash, "",
         "namespace lynx::splashdata", "{", "inline constexpr unsigned char markPng[] = {"]
for i in range(0, len(data), 24):
    lines.append(", ".join(str(b) for b in data[i:i + 24]) + ",")
lines += ["};", "} // namespace lynx::splashdata", ""]
open("src/ui/SplashData.h", "w").write("\n".join(lines))
print(width, HEIGHT, len(data), "bytes")
